"""Validate benchmark submissions and render the leaderboard.

    python benchmark/leaderboard.py          # write LEADERBOARD.md
    python benchmark/leaderboard.py --check   # CI: non-zero exit if invalid or stale

Output is deterministic (no timestamps) so ``--check`` is a stable up-to-date test.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

BENCH_DIR = Path(__file__).resolve().parent
SUBMISSIONS_DIR = BENCH_DIR / "submissions"
LEADERBOARD_MD = BENCH_DIR.parent / "LEADERBOARD.md"

# Track order, titles, and the metric each track ranks by.
TRACKS = {
    "forensynths": {
        "title": "ForenSynths — image (ProGAN-trained, cross-generator)",
        "primary": "map", "modality": "image",
    },
    "genimage-sdv1.4": {
        "title": "GenImage SD-v1.4 — image", "primary": "auroc", "modality": "image",
    },
    "genvideo-val": {
        "title": "GenVideo-Val — video", "primary": "ap", "modality": "video",
    },
}
METRIC_COLS = [("acc", "Acc"), ("map", "mAP"), ("ap", "AP"), ("auroc", "AUROC")]
EVALUATIONS = {"official-weights", "from-scratch", "frozen-probe", "training-free", "external"}
MODALITIES = {"image", "video"}
REQUIRED = ["method", "track", "modality", "evaluation", "metrics", "submitted_by"]


def validate(sub: dict, where: str) -> list[str]:
    """Return a list of human-readable errors for one submission (empty = valid)."""
    errs = []
    for k in REQUIRED:
        if k not in sub:
            errs.append(f"missing required field '{k}'")
    if sub.get("track") not in TRACKS:
        errs.append(f"track '{sub.get('track')}' not in {sorted(TRACKS)}")
    if sub.get("modality") not in MODALITIES:
        errs.append(f"modality '{sub.get('modality')}' not in {sorted(MODALITIES)}")
    if sub.get("evaluation") not in EVALUATIONS:
        errs.append(f"evaluation '{sub.get('evaluation')}' not in {sorted(EVALUATIONS)}")
    metrics = sub.get("metrics")
    if not isinstance(metrics, dict):
        errs.append("'metrics' must be an object")
    else:
        vals = [metrics.get(m) for m, _ in METRIC_COLS]
        if not any(isinstance(v, (int, float)) for v in vals):
            errs.append("'metrics' needs at least one numeric value among acc/map/ap/auroc")
    return [f"{where}: {e}" for e in errs]


def load_submissions():
    """Return (valid_submissions, errors)."""
    subs, errors = [], []
    for path in sorted(SUBMISSIONS_DIR.glob("*.json")):
        try:
            sub = json.loads(path.read_text())
        except json.JSONDecodeError as exc:
            errors.append(f"{path.name}: invalid JSON ({exc})")
            continue
        errs = validate(sub, path.name)
        if errs:
            errors.extend(errs)
            continue
        sub["_file"] = path.name
        subs.append(sub)
    return subs, errors


def _fmt(v) -> str:
    return f"{v:.2f}" if isinstance(v, (int, float)) else "—"


def _sort_key(sub, primary):
    v = sub.get("metrics", {}).get(primary)
    # rank desc by primary; missing primary sorts last
    return (0, -v) if isinstance(v, (int, float)) else (1, 0.0)


def render() -> str:
    subs, errors = load_submissions()
    lines = [
        "# SynthScope Leaderboard (v1)", "",
        "_Auto-generated by `benchmark/leaderboard.py` — do not edit by hand._ "
        "See [benchmark/README.md](benchmark/README.md) for the protocol and how to submit.",
        "", "This is the **standardized, versioned** table: a few tracks with a fixed protocol that anyone can submit to. The web page's **Leaderboard** tab is broader (every paper benchmark, 30+ groups) and the repo supports many more datasets, which download and organize themselves: see [docs/BENCHMARKS.md](docs/BENCHMARKS.md).", "",
        "Metrics are percentages. **mAP** = mean AP over generators. Each track is ranked by "
        "its primary metric (in bold).", "",
    ]
    for track_id, cfg in TRACKS.items():
        rows = [s for s in subs if s.get("track") == track_id]
        primary = cfg["primary"]
        header_cells = ["Rank", "Method", "Eval"]
        for key, label in METRIC_COLS:
            header_cells.append(f"**{label}**" if key == primary else label)
        header_cells += ["Verified", "Notes"]
        lines.append(f"## {cfg['title']}")
        lines.append("")
        if not rows:
            lines += ["_No submissions yet._", ""]
            continue
        rows.sort(key=lambda s: _sort_key(s, primary))
        lines.append("| " + " | ".join(header_cells) + " |")
        lines.append("| " + " | ".join(["---"] * len(header_cells)) + " |")
        for i, s in enumerate(rows, 1):
            m = s.get("metrics", {})
            cells = [str(i), s["method"], s["evaluation"]]
            cells += [_fmt(m.get(key)) for key, _ in METRIC_COLS]
            cells.append("✓" if s.get("verified") else "")
            note = s.get("protocol_notes") or ""
            cells.append(note.replace("|", "/"))
            lines.append("| " + " | ".join(cells) + " |")
        lines.append("")
    if errors:
        lines += ["## ⚠️ Invalid submissions", ""] + [f"- {e}" for e in errors] + [""]
    return "\n".join(lines).rstrip() + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Build/validate the SynthScope leaderboard.")
    ap.add_argument("--check", action="store_true",
                    help="validate submissions and verify LEADERBOARD.md is up to date (CI)")
    args = ap.parse_args(argv)

    subs, errors = load_submissions()
    content = render()

    if args.check:
        ok = True
        if errors:
            print("Invalid submissions:", file=sys.stderr)
            for e in errors:
                print(f"  - {e}", file=sys.stderr)
            ok = False
        current = LEADERBOARD_MD.read_text() if LEADERBOARD_MD.exists() else ""
        if current != content:
            print("LEADERBOARD.md is stale — run `python benchmark/leaderboard.py`.", file=sys.stderr)
            ok = False
        if ok:
            print(f"OK: {len(subs)} submissions, leaderboard up to date.")
        return 0 if ok else 1

    LEADERBOARD_MD.write_text(content)
    print(f"Wrote {LEADERBOARD_MD} ({len(subs)} submissions"
          + (f", {len(errors)} invalid" if errors else "") + ").")
    for e in errors:
        print(f"  invalid: {e}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
